#!/usr/bin/env -S uv run
"""
The appendix topics table (tab:topics): accuracy by exam topic for each
model, with one panel per condition and an all-model mean last. Reads
data/figures/per_question.csv and writes $PAPER_DIR/tables/topics.tex.

A cell is the mean of per-question accuracy over the topic's questions, so
each question counts once. Rows follow the exam's category tree, with small
categories folded into neighbouring rows (TOPICS) so that every row has at
least four questions. Emits the `tabular` block only. Requires `booktabs`
and `threeparttable`.

Usage:
    python3 scripts/figures/table_topics.py
"""
from __future__ import annotations

import csv
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "misc"))

import hub_jobs  # noqa: E402
import style  # noqa: E402

DATA_PATH = style.REPO_DIR / "data" / "figures" / "per_question.csv"

# Leaf section number (the part of the category before the colon) -> row.
# The six key-term sections with one to three questions each (9 in all)
# share a row, labelled "Key terms" with a footnote under the table listing
# them and their question counts (OTHER_SECTIONS, counted from the data). The
# two key-term sections big enough for their own rows (reduction
# calculations, severe fragmentation) drop the "Key terms:" prefix; the
# footnote's list is what says which terms the pooled row covers.
# C2 (3) and D (1) share a row; the regional module's four sections (1-6
# questions each) are one row; 2.1 (one question on the threatened
# categories) joins 2.2.
OTHER_TERMS = r"Key terms\tnote{*}"
OTHER_SECTIONS = {
    "3.1": "generation length",
    "3.3": "continuing decline",
    "3.4": "EOO/AOO",
    "3.5": "mature individuals",
    "3.6": "extreme fluctuation",
    "3.8": "locations",
}
TOPICS = {
    "1": "General rules",
    "2.1": "Red List categories",
    "2.2": "Red List categories",
    "3.1": OTHER_TERMS,
    "3.2": "Reduction calculations",
    "3.3": OTHER_TERMS,
    "3.4": OTHER_TERMS,
    "3.5": OTHER_TERMS,
    "3.6": OTHER_TERMS,
    "3.7": "Severe fragmentation",
    "3.8": OTHER_TERMS,
    "4.1": "Criterion A",
    "4.2": "Criterion B",
    "4.3": "Criterion C1",
    "4.4": "Criteria C2 and D",
    "4.5": "Criteria C2 and D",
    "4.6": "Criterion E",
    "5": "Supporting information",
    "6": "Mapping standards",
    "7.1": "Regional assessments",
    "7.2": "Regional assessments",
    "7.3": "Regional assessments",
    "7.4": "Regional assessments",
}

MEAN = "Mean"
# A wide gap before the mean column, to set the summary apart from the
# per-model columns.
MEAN_GAP = r"@{\hspace{2\tabcolsep}\hspace{1.8em}}"

# Notes on the table, kept out of the generated .tex:
# Wrapped in its float, captioned and labelled by main.tex. One panel per
# condition: (a) guidelines, (b) closed-book.
# A cell is the model's mean per-question accuracy over the topic's n
# questions, in whole percent; "Mean" averages the same per-question
# accuracies over the models. Rows follow the exam's section order.
# Small-n rows are noisy.
NOTE = r"""%% GENERATED by scripts/figures/table_topics.py -- do not edit by hand."""


def section(category: str) -> str:
    """"4: M3 - Red List Criteria/4.1: Criterion A" -> "4.1".

    Takes the last numbered heading rather than the last path segment, since
    one leaf title itself contains a slash ("7.1: Downlisting // Uplisting")."""
    return re.findall(r"(\d+(?:\.\d+)?):", category)[-1]


def load(models: list[str], condition: str) -> tuple[dict, dict, dict]:
    """(accuracy, topic, sections): accuracy[(model, task)] is that model's
    per-question accuracy in `condition`, topic[task] is the question's table
    row, and sections[task] its exam section number."""
    accuracy, topic, sections = {}, {}, {}
    with DATA_PATH.open() as handle:
        for row in map(style.paper_name, csv.DictReader(handle)):
            if row["model"] not in models or row["condition"] != condition:
                continue
            key = section(row["category"])
            if key not in TOPICS:
                raise SystemExit(f"{row['task']}: category {row['category']!r} has no row in TOPICS")
            topic[row["task"]] = TOPICS[key]
            sections[row["task"]] = key
            accuracy[(row["model"], row["task"])] = (
                int(row["n_correct"]) / int(row["n_attempts"])
            )
    # Every model must have every question, or a column would average over a
    # different question set from its neighbours.
    for task in topic:
        for model in models:
            if (model, task) not in accuracy:
                raise SystemExit(f"{task}: no {model} / {condition} result")
    return accuracy, topic, sections


def other_footnote(sections: dict) -> str:
    """"*Generation length (1), continuing decline (3), ..." with each pooled
    section's question count."""
    counts = {key: sum(1 for s in sections.values() if s == key) for key in OTHER_SECTIONS}
    parts = [f"{name} ({counts[key]})" for key, name in OTHER_SECTIONS.items() if counts[key]]
    listed = ", ".join(parts[:-1]) + " and " + parts[-1]
    return f"{listed[0].upper()}{listed[1:]}."


def cells(tasks: list[str], models: list[str], accuracy: dict) -> dict[str, float]:
    """column -> accuracy in percent for one row, where column is a model or
    MEAN."""
    out = {
        model: 100 * statistics.mean(accuracy[(model, t)] for t in tasks)
        for model in models
    }
    out[MEAN] = 100 * statistics.mean(
        statistics.mean(accuracy[(m, t)] for m in models) for t in tasks
    )
    return out


def line(label: str, n: int, values: dict, columns: list[str]) -> str:
    numbers = [f"{values[column]:.0f}" for column in columns]
    return " & ".join([label, str(n), *numbers]) + r" \\"


def spec(columns: list[str]) -> str:
    # The same wide gap after n as before the mean: n is a count and the
    # columns after it are percentages, so the gap keeps it from reading as
    # one more accuracy.
    return "lr" + MEAN_GAP + "".join(
        (MEAN_GAP if column == MEAN else "") + "r" for column in columns
    )


def header(columns: list[str], dirs: dict[str, str]) -> list[str]:
    """The column-heading rows: "Accuracy (%)" over the model and mean
    columns, the unit the caption would otherwise have to carry alone, then
    one heading per column. Repeated in each panel rather than given once,
    since a model heading links to that condition's own Hub job."""
    heads = " & ".join(
        hub_jobs.link(style.column_head(c), dirs[c]) if c in dirs else style.column_head(c)
        for c in columns
    )
    return [
        rf" & & \multicolumn{{{len(columns)}}}{{c}}{{Accuracy (\%)}} \\",
        rf"\cmidrule(l){{3-{2 + len(columns)}}}",
        rf"Topic & $n$ & {heads} \\",
    ]


def panel(index: int, condition: str, results: list[dict]) -> tuple[list[str], list[str], dict]:
    """(columns, rows, sections) for one condition's panel: rows run from the
    panel heading to the "All questions" row."""
    models = style.models_in(results, condition)
    accuracy, topic, sections = load(models, condition)
    columns = [*models, MEAN]

    tasks_by_topic: dict[str, list[str]] = defaultdict(list)
    for task, name in sorted(topic.items()):
        tasks_by_topic[name].append(task)

    def exam_order(name: str) -> tuple:
        """Module, then the pooled row after its module's named rows, then
        the row's first section number ("4.10" after "4.9")."""
        first = min((tuple(int(part) for part in sections[t].split(".")) for t in tasks_by_topic[name]))
        return (first[0], name == OTHER_TERMS, first)

    rows = [
        (cells(tasks_by_topic[name], models, accuracy), name, tasks_by_topic[name])
        for name in sorted(tasks_by_topic, key=exam_order)
    ]
    body = [line(name, len(tasks), values, columns) for values, name, tasks in rows]
    overall = line("All questions", len(topic), cells(sorted(topic), models, accuracy), columns)
    print(f"  {condition}: {len(topic)} questions, models: {', '.join(models)}")
    return columns, [
        style.panel_heading(index, condition, 2 + len(columns)),
        *header(columns, hub_jobs.job_dirs(results, condition)),
        r"\midrule", *body, r"\midrule", overall,
    ], sections


def main() -> None:
    # generation="all": every model the results table has, in the same
    # release order, so this table is that table sliced rather than a
    # different population.
    results = style.load_results(generation="all")
    panels = [panel(i, condition, results) for i, condition in enumerate(style.SPLIT_CONDITIONS)]
    columns, _, sections = panels[0]
    # One tabular, so every panel needs the same columns -- and the same
    # questions, or the shared footnote's counts would be one panel's only.
    assert all(p[0] == columns and p[2] == sections for p in panels), "panels differ"

    body = []
    for i, (_, rows, _) in enumerate(panels):
        body += [r"\toprule" if i == 0 else style.PANEL_RULE, *rows]
    notes = [
        r"\begin{tablenotes}\scriptsize\raggedright",  # justified, it stretches word gaps
        rf"\item[*] {other_footnote(sections)}",
        r"\end{tablenotes}",
    ]
    # The two size settings go before threeparttable so they apply to the
    # notes as well as the tabular.
    latex = "\n".join([NOTE, r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
                       r"\begin{threeparttable}", rf"\begin{{tabular}}{{{spec(columns)}}}",
                       *body, r"\bottomrule", r"\end{tabular}",
                       *notes, r"\end{threeparttable}", ""])
    style.TABLES_DIR.mkdir(parents=True, exist_ok=True)
    path = style.TABLES_DIR / "topics.tex"
    path.write_text(latex)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
