#!/usr/bin/env -S uv run
"""
The appendix errors table (tab:errors): correct answers and each kind of
wrong answer, by question type (category, multiple select, calculation,
matching) and model, with one panel per condition. Reads
data/figures/outcomes.csv and writes $PAPER_DIR/tables/errors.tex.

Cells are attempt counts, so a group's rows add up to 5n per model, and
the last column gives all models together as a count and a share. Emits the
`tabular` block only. Requires `booktabs`.

Usage:
    python3 scripts/figures/table_errors.py
"""
from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "misc"))

import hub_jobs  # noqa: E402
import style  # noqa: E402

DATA_PATH = style.REPO_DIR / "data" / "figures" / "outcomes.csv"
ALL_GAP = r"@{\hspace{2\tabcolsep}\hspace{1.8em}}"

# (question type, heading, [(row label, outcome)]). Every outcome that
# build_outcome_data.py writes for a question type must be listed under it;
# rows that no model hit in either condition are dropped.
GROUPS = [
    ("category", "Category questions", [
        ("Correct", "correct"),
        ("Category one step off on the threat scale", "category_one_step"),
        ("Category further off, or a non-threat category", "category_further"),
        ("Right category and criterion, extra subcriteria", "code_extra_subcriteria"),
        ("Right category, criteria added when not asked for", "code_extra_criteria"),
        ("Right category, subcriteria or numerals wrong", "code_subcriteria"),
        ("Right category, criterion wrong", "code_criterion"),
        ("Right category, criteria missing", "code_missing"),
        ("Right category, spacing only", "code_formatting"),
        ("No answer written", "no_answer"),
    ]),
    ("multi", "Multiple-select questions", [
        ("Correct", "correct"),
        ("Right options plus an extra", "multi_extra"),
        ("A right option missed", "multi_missed"),
        ("Other wrong set", "multi_wrong"),
        ("No answer written", "no_answer"),
    ]),
    ("calculation", "Calculation questions", [
        ("Correct", "correct"),
        ("Wrong number", "numeric"),
        ("No answer written", "no_answer"),
    ]),
    ("matching", "Matching questions", [
        ("Correct", "correct"),
        ("Pairs wrong", "matching"),
        ("No answer written", "no_answer"),
    ]),
    ("other", "Other questions", [
        ("Correct", "correct"),
        ("Wrong answer", "other"),
        ("No answer written", "no_answer"),
    ]),
]

# Notes on the table, kept out of the generated .tex:
# Wrapped in its float, captioned and labelled by main.tex. One panel per
# condition: (a) guidelines, (b) closed-book.
# Attempts by outcome, grouped by question type; each group's rows add up to
# 5n attempts per model (n questions, five attempts each). "All" gives every
# model together as count and share of that question type's attempts.
NOTE = r"""%% GENERATED by scripts/figures/table_errors.py -- do not edit by hand."""


def panel(index: int, condition: str, results: list[dict]) -> tuple[list[str], list[str]]:
    """(models, rows) for one condition's panel, from its heading row to its
    last outcome row."""
    models = style.models_in(results, condition)

    counts: Counter = Counter()
    questions: dict[str, set] = {}
    with DATA_PATH.open() as handle:
        for row in map(style.paper_name, csv.DictReader(handle)):
            if row["model"] in models and row["condition"] == condition:
                key = (row["question_type"], row["model"], row["outcome"])
                counts[key] += int(row["attempts"])
                questions.setdefault(row["question_type"], set()).add(row["task"])

    listed = {(qt, outcome) for qt, _, rows in GROUPS for _, outcome in rows}
    unlisted = {(qt, o) for (qt, _, o) in counts} - listed
    if unlisted:
        raise SystemExit(f"outcomes missing from GROUPS: {sorted(unlisted)}")

    def cells(qtype: str, outcome: str) -> list[str]:
        out = [str(counts[(qtype, m, outcome)]) for m in models]
        n = sum(counts[(qtype, m, outcome)] for m in models)
        total = sum(v for (qt, _, _), v in counts.items() if qt == qtype)
        out.append(rf"{n} ({100 * n / total:.0f}\%)")
        return out

    width = 2 + len(models)
    dirs = hub_jobs.job_dirs(results, condition)
    # The heading row is repeated in each panel rather than given once, since
    # a model heading links to that condition's own Hub job.
    heads = " & ".join([*(hub_jobs.link(style.column_head(m), dirs[m]) for m in models),
                        style.column_head("All")])
    lines = [
        style.panel_heading(index, condition, width),
        rf"Question type and outcome & {heads} \\",
        r"\midrule",
    ]
    body = []
    for qtype, heading, rows in GROUPS:
        if qtype not in questions:
            continue
        if body:
            lines.append(r"\addlinespace")
        lines.append(rf"\multicolumn{{{width}}}{{l}}{{\textbf{{{heading}}} ($n={len(questions[qtype])}$)}} \\")
        for label, outcome in rows:
            if not any(counts[(qtype, m, outcome)] for m in models):
                continue
            row = " & ".join([rf"\quad {label}", *cells(qtype, outcome)]) + r" \\"
            body.append(row)
            lines.append(row)
    assert all(row.count("&") == width - 1 for row in body), "column count"
    print(f"  {condition}: {sum(len(q) for q in questions.values())} questions, models: {', '.join(models)}")
    return models, lines


def main() -> None:
    # generation="all": every model the results table has, in the same
    # release order, so this table is that table sliced rather than a
    # different population.
    results = style.load_results(generation="all")
    panels = [panel(i, condition, results) for i, condition in enumerate(style.SPLIT_CONDITIONS)]
    models = panels[0][0]
    # One tabular, so every panel needs the same columns.
    assert all(p[0] == models for p in panels), "panels differ in models"

    lines = [
        NOTE,
        r"\footnotesize",
        # 3pt rather than the 4pt the other breakdowns use: this is the
        # widest of them (twelve number columns against a row label as long
        # as "Right category, criteria added when not asked for"), and 4pt
        # put it 10pt over the text width.
        r"\setlength{\tabcolsep}{3pt}",
        rf"\begin{{tabular}}{{l{'r' * len(models)}{ALL_GAP}r}}",
    ]
    for i, (_, rows) in enumerate(panels):
        lines += [r"\toprule" if i == 0 else style.PANEL_RULE, *rows]
    lines += [r"\bottomrule", r"\end{tabular}", ""]

    style.TABLES_DIR.mkdir(parents=True, exist_ok=True)
    path = style.TABLES_DIR / "errors.tex"
    path.write_text("\n".join(lines))
    print(f"wrote {path}")

if __name__ == "__main__":
    main()
