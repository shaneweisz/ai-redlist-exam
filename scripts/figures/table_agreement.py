#!/usr/bin/env -S uv run
"""
The main-text agreement table (tab:agreement), summarising the appendix
votes table: for each model with the guidelines, how many of the 101
questions its five attempts were unanimous on, and how often the majority
vote was right on those versus the rest. Reads data/figures/votes.csv
through table_votes.tally and writes $PAPER_DIR/tables/agreement.tex.

The pooled row pools over every model-question pair, as the votes table
does. Emits the `tabular` block only. Requires `booktabs`.

Usage:
    python3 scripts/figures/table_agreement.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "misc"))

import hub_jobs  # noqa: E402
import style  # noqa: E402
import table_votes  # noqa: E402

CONDITION = "Guidelines"

# Notes on the table, kept out of the generated .tex:
# Wrapped in its float, captioned and labelled in the results section.
# Guidelines condition only; closed-book and the per-split detail are in
# the appendix votes table (tables/votes.tex), which this summarises.
# "All models (pooled)": mean unanimous count; accuracies pooled over all
# model-question pairs, as in the appendix table.
NOTE = r"""%% GENERATED by scripts/figures/table_agreement.py -- do not edit by hand."""


def main() -> None:
    results = style.load_results(generation="all")
    models, questions, correct = table_votes.tally(CONDITION, results)
    unanimous = table_votes.UNANIMOUS

    def row(ms: list[str]) -> tuple[float, float, float]:
        """(unanimous questions per model, % correct on them, % on the rest)."""
        n_u = sum(questions[(m, unanimous)] for m in ms)
        k_u = sum(correct[(m, unanimous)] for m in ms)
        rest = [(m, s) for m in ms for s in table_votes.ORDER if s != unanimous]
        n_r = sum(questions[key] for key in rest)
        k_r = sum(correct[key] for key in rest)
        return n_u / len(ms), 100 * k_u / n_u, 100 * k_r / n_r if n_r else float("nan")

    dirs = hub_jobs.job_dirs(results, CONDITION)
    body = []
    for model in models:
        n, u, r = row([model])
        body.append(" & ".join([hub_jobs.link(style.SHORT_NAMES.get(model, model), dirs[model]),
                                f"{n:.0f}", f"{u:.0f}", f"{r:.0f}"]) + r" \\")
    n, u, r = row(models)
    pooled = " & ".join([r"\textit{All models (pooled)}", f"{n:.1f}", f"{u:.0f}", f"{r:.0f}"]) + r" \\"

    lines = [
        NOTE,
        r"\footnotesize",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r" & & \multicolumn{2}{c}{Majority-vote answer correct (\%)} \\",
        r"\cmidrule(lr){3-4}",
        r"Model & \begin{tabular}[b]{@{}r@{}}Unanimous\\(of 101)\end{tabular} & When unanimous & When split \\",
        r"\midrule",
        *body,
        r"\midrule",
        pooled,
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    style.TABLES_DIR.mkdir(parents=True, exist_ok=True)
    path = style.TABLES_DIR / "agreement.tex"
    path.write_text("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
