#!/usr/bin/env -S uv run
"""
The appendix results table (tab:results), for every model in every
condition: accuracy (mean, maj@5, pass^5, pass@5), latency, tokens per
question and API cost. Reads data/figures/results.csv and writes
$PAPER_DIR/tables/results.tex.

Emits the `tabular` block only; main.tex owns the float and the caption.
Requires `booktabs`. Models are grouped by vendor and serving path
(style.VENDOR_GROUPS), newest first, with each model's conditions on
adjacent rows.

Usage:
    python3 scripts/figures/table_results.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "misc"))

import hub_jobs  # noqa: E402
import style  # noqa: E402

# Columns in the tabular: the label plus every number. Both the model
# headings and the block headings span the whole table, so they read it from
# here rather than each hardcoding a count that the next added column breaks.
N_COLUMNS = 13

SERVING = {
    "claude-code": "Anthropic API",
    "opencode (local Mac Studio, M2 Ultra)": "self-hosted",
    # GPT-6 models run through OpenAI's Codex CLI against a ChatGPT
    # subscription rather than a metered API key, so per-question USD is
    # not meaningful for them the way it is for the Anthropic rows.
    "codex": "OpenAI, Codex CLI",
}

# Notes on the table, kept out of the generated .tex:
# Wrapped in its float, captioned and labelled by main.tex.
# tok/s is output tokens over agent wall-clock. It reflects the serving path
# as much as the model -- Anthropic's API, OpenAI's, and a local Mac Studio
# via Ollama are different pipes -- so it is not a like-for-like model
# comparison across serving paths. Within
# one serving path it is informative, and inverts the mean s ordering:
# Sonnet 5 generates fastest of the four current Claude rows and still takes
# longest per question, because it writes 3.2x the output tokens Opus 5.5
# does.
# USD / q is always PUBLISHED API RATES x real measured tokens, never a
# figure anyone was billed. That matters for the GPT-6 rows: those runs went
# through a ChatGPT subscription, so their marginal cost was zero and the
# USD shown is what the same tokens would have cost on the metered API. It
# is the right number for comparing models, the wrong one for reconstructing
# a bill. (Self-hosted rows show n/a: there is no
# per-token charge for them. That is not a claim that they cost nothing to
# run -- hardware and electricity are outside this column, hence "API cost".)
# Token columns are non-overlapping and sum to the whole prompt plus
# completion: "in" is input neither read from nor written to the prompt
# cache, cache "write" is written to it (billed at 1.25x input for 5-minute writes,
# 2x for 1-hour), cache "read" is served from it (0.1x; 0.05x for Opus 5.5). Cache write dwarfs "in" on every metered row --
# that is the harness caching its prefix, not a typo. "total" is their sum,
# the quantity the token panels of Figures 2 and 3 plot.
# SE is the run-to-run standard error over the five repeats of the exam
# (std of the five per-round scores / sqrt(5)); Figure 1's whiskers are the
# same quantity as a 95% interval, 1.96 x SE.
HEADER = r"""%% GENERATED by scripts/figures/table_results.py -- do not edit by hand.
\footnotesize
\setlength{\tabcolsep}{4.2pt}
\begin{tabular}{lrrrrrrrrrrrr}
\toprule
 & \multicolumn{4}{c}{Accuracy (\%)} & \multicolumn{2}{c}{Latency} & \multicolumn{5}{c}{Tokens / question} & API cost \\
\cmidrule(lr){2-5} \cmidrule(lr){6-7} \cmidrule(lr){8-12}
 & & & & & & & & \multicolumn{2}{c}{cache} & & & \\
\cmidrule(lr){9-10}
Model and condition & mean $\pm$ SE & maj@5 & pass$^5$ & pass@5 & mean s & tok/s & in & write & read & out & total & USD / q \\
\midrule"""

FOOTER = r"""\bottomrule
\end{tabular}"""


def thousands(value: float | None) -> str:
    if value is None:
        return "--"
    if value >= 10_000:
        return f"{value / 1000:.0f}k"
    if value >= 1000:
        return f"{value / 1000:.1f}k"
    return f"{value:.0f}"


CONDITION_NAMES = {
    "Guidelines": "Guidelines",
    "Closed-book": "Closed-book",
}


def mean_accuracy(row: dict) -> str:
    """Mean accuracy over all attempts with its run-to-run standard error.

    The SE itself, not the 1.96x half-width Figure 1's whiskers draw -- a
    table is read for the numbers and SE is the one a reader can rescale to
    whatever interval they want. Single-attempt jobs have no rerun spread
    and get the bare score."""
    if row["accuracy_se"] is None:
        return f"{row['accuracy_avg']:.1f}"
    return rf"{row['accuracy_avg']:.1f} $\pm$ {row['accuracy_se']:.1f}"


def dollars(row: dict) -> str:
    if row["is_local"]:
        # No API price: there is no per-token charge for a self-hosted model.
        # "n/a" rather than "0", which read as the run costing nothing -- the
        # hardware and the electricity are real and are simply outside what
        # this (API cost) column measures. Matches Figure 2's cost panel.
        return "n/a"
    if row["mean_usd_per_task"] is None:
        return "--"
    return f"{row['mean_usd_per_task']:.3f}"


def escape(text: str) -> str:
    return text.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def body_rows(rows: list[dict], models: list[str]) -> list[str]:
    by_key = {(row["model"], row["condition"]): row for row in rows}
    lines: list[str] = []
    for index, model in enumerate(models):
        # A model only lists the conditions it actually ran.
        model_rows = [by_key[(model, c)] for c in style.TABLE_CONDITIONS if (model, c) in by_key]
        if index:
            lines.append(r"\addlinespace")
        # The group heading names the vendor and the serving path, so the
        # per-model note is the release month alone. SERVING covers a
        # harness with no group of its own.
        details = f"released {style.RELEASED[model]}" if model in style.RELEASED \
            else SERVING.get(model_rows[0]["harness"], "--")
        lines.append(rf"\multicolumn{{{N_COLUMNS}}}{{l}}{{\textbf{{{escape(style.FULL_NAMES.get(model, model))}}} \enspace \textit{{{details}}}}} \\")
        for row in model_rows:
            lines.append(
                " & ".join([
                    r"\quad " + hub_jobs.link(CONDITION_NAMES[row["condition"]], row["job_dir"]),
                    mean_accuracy(row),
                    f"{row['majority_accuracy']:.1f}" if row["majority_accuracy"] is not None else "--",
                    f"{row['pass_hat_5']:.1f}" if row["pass_hat_5"] is not None else "--",
                    f"{row['pass_at_5']:.1f}" if row["pass_at_5"] is not None else "--",
                    f"{row['mean_seconds_per_task']:.0f}",
                    f"{row['tokens_per_sec']:.0f}" if row["tokens_per_sec"] else "--",
                    thousands(row["input_tokens_per_task"]),
                    thousands(row["cache_write_tokens_per_task"]),
                    thousands(row["cache_read_tokens_per_task"]),
                    thousands(row["output_tokens_per_task"]),
                    thousands(row["total_tokens_per_task"]),
                    dollars(row),
                ])
                + r" \\"
            )
    return lines


def build(out_name: str) -> None:
    # Grouped by vendor and serving path (style.VENDOR_GROUPS), newest model
    # first inside each group.
    rows = style.load_results(generation="all")
    body: list[str] = []
    for heading, models in style.grouped_order(rows):
        group = [r"\addlinespace"] if body else []
        group.append(rf"\multicolumn{{{N_COLUMNS}}}{{l}}{{\textsc{{{escape(heading)}}}}} \\")
        group.append(r"\addlinespace")
        group.extend(body_rows(rows, models))
        body.extend(group)
    latex = "\n".join([HEADER, *body, FOOTER, ""])
    out = style.TABLES_DIR / out_name
    out.write_text(latex)
    print(f"wrote {out}")


def main() -> None:
    style.TABLES_DIR.mkdir(parents=True, exist_ok=True)
    build("results.tex")


if __name__ == "__main__":
    main()
